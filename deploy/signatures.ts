/**
 * Refreshes src/recipes/signatures.generated.ts from the OWASP Core Rule Set data files
 * (Apache-2.0): known scanner User-Agents and the "restricted files" list (dotfiles,
 * credentials, config files nobody fetches by accident). Run `npm run signatures:update`,
 * review the diff, commit. Runs in Node only; never bundled.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const BASE = 'https://raw.githubusercontent.com/coreruleset/coreruleset/main/rules/';
const FILES = { agents: 'scanners-user-agents.data', files: 'restricted-files.data' } as const;

async function fetchList(name: string): Promise<string[]> {
  const res = await fetch(BASE + name);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  return (await res.text())
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'));
}

const agents = (await fetchList(FILES.agents)).map((a) => a.toLowerCase());
// Entries are file or directory names that may appear anywhere in a path; keep them lower-case.
const files = (await fetchList(FILES.files)).map((f) => f.toLowerCase());

const out = `// Generated by deploy/signatures.ts on ${new Date().toISOString().slice(0, 10)} — do not edit.
// Source: OWASP Core Rule Set (https://github.com/coreruleset/coreruleset), Apache License 2.0.
//   rules/${FILES.agents} (${agents.length} entries), rules/${FILES.files} (${files.length} entries).

/** Substrings of User-Agent headers used by vulnerability scanners and fuzzers (lower-case). */
export const CRS_SCANNER_AGENTS: readonly string[] = ${JSON.stringify(agents, null, 0)};

/** File and directory names that only scanners ask for (lower-case; matched after a "/"). */
export const CRS_RESTRICTED_FILES: readonly string[] = ${JSON.stringify(files, null, 0)};
`;
const path = resolve(process.cwd(), 'src/recipes/signatures.generated.ts');
writeFileSync(path, out);
console.log(`wrote ${path}: ${agents.length} agents, ${files.length} files`);
